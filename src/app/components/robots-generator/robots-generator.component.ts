import { Component, signal, computed } from '@angular/core';
import { CommonModule } from '@angular/common';
import { FormsModule } from '@angular/forms';

interface RobotRule {
  id: number;
  userAgent: string;
  allowPaths: string[];
  disallowPaths: string[];
  crawlDelay?: number;
}

@Component({
  selector: 'app-robots-generator',
  standalone: true,
  imports: [CommonModule, FormsModule],
  templateUrl: './robots-generator.component.html',
  styleUrl: './robots-generator.component.scss'
})
export class RobotsGeneratorComponent {
  rules = signal<RobotRule[]>([
    {
      id: 1,
      userAgent: '*',
      allowPaths: ['/'],
      disallowPaths: ['/admin/', '/private/', '/api/'],
      crawlDelay: 2
    }
  ]);

  sitemapUrl = signal<string>('https://example.com/sitemap.xml');
  hostUrl = signal<string>('https://example.com');

  generatedRobotsTxt = computed(() => {
    let out = '# robots.txt generated by FreeTools\n\n';

    for (const rule of this.rules()) {
      out += `User-agent: ${rule.userAgent}\n`;
      for (const a of rule.allowPaths) {
        if (a.trim()) out += `Allow: ${a.trim()}\n`;
      }
      for (const d of rule.disallowPaths) {
        if (d.trim()) out += `Disallow: ${d.trim()}\n`;
      }
      if (rule.crawlDelay && rule.crawlDelay > 0) {
        out += `Crawl-delay: ${rule.crawlDelay}\n`;
      }
      out += '\n';
    }

    if (this.sitemapUrl().trim()) {
      out += `Sitemap: ${this.sitemapUrl().trim()}\n`;
    }
    if (this.hostUrl().trim()) {
      out += `Host: ${this.hostUrl().trim()}\n`;
    }

    return out.trim();
  });

  addRule() {
    this.rules.update(list => [
      ...list,
      {
        id: Date.now(),
        userAgent: 'Googlebot',
        allowPaths: ['/'],
        disallowPaths: ['/no-google/']
      }
    ]);
  }

  removeRule(id: number) {
    this.rules.update(list => list.filter(r => r.id !== id));
  }

  addAllowPath(rule: RobotRule) {
    rule.allowPaths.push('/');
    this.rules.set([...this.rules()]);
  }

  addDisallowPath(rule: RobotRule) {
    rule.disallowPaths.push('/path/');
    this.rules.set([...this.rules()]);
  }

  copyRobots() {
    navigator.clipboard.writeText(this.generatedRobotsTxt());
  }

  downloadRobots() {
    const blob = new Blob([this.generatedRobotsTxt()], { type: 'text/plain' });
    const link = document.createElement('a');
    link.href = URL.createObjectURL(blob);
    link.download = 'robots.txt';
    link.click();
  }
}

